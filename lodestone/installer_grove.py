def _unit(description: str, user: str, env_file: str, module: str, writable: str = "", memory: str = "512M") -> str:
    lines = ["[Unit]", "Description=" + description, "After=network-online.target", "Wants=network-online.target", "",
             "[Service]", "Type=simple", "User=" + user, "Group=" + user,
             "WorkingDirectory=" + (NATIVE_DATA if writable else "/"), "EnvironmentFile=" + env_file,
             "ExecStart=%s/bin/python -m %s" % (NATIVE_VENV, module), "Restart=on-failure", "RestartSec=5",
             "NoNewPrivileges=true", "ProtectSystem=strict", "ProtectHome=true", "PrivateTmp=true", "PrivateDevices=true",
             "ProtectKernelTunables=true", "ProtectControlGroups=true", "RestrictAddressFamilies=AF_INET AF_INET6 AF_UNIX",
             "CapabilityBoundingSet=", "MemoryMax=" + memory]
    if writable:
        lines.append("ReadWritePaths=" + writable)
    return "\n".join(lines) + "\n\n[Install]\nWantedBy=multi-user.target\n"


