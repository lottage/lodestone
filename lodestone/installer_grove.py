def _hardened() -> Dict[str, Any]:
    return {"read_only": True, "tmpfs": ["/tmp"], "cap_drop": ["ALL"], "security_opt": ["no-new-privileges:true"]}


def add_to_compose(svc: Dict[str, Any], stack: Dict[str, Any], layer_image: Callable[..., str], build_context: Callable[..., str],
                   engine_urls: Dict[str, str]) -> None:
    """Add Grove to the services mapping that installer.compose_services built (in place): the cockpit runs the plugin (an image made
    FROM the Hearth one), and three services are new. Never network_mode host; no secret in the file (`${VAR:?}` from .env)."""
    g, tag, build = stack["garden"], stack["tag"], bool(stack.get("build"))
    st = svc["stonesage"]
    if build:
        # Hearth is built by a one-shot service of its own, then the Grove image is built FROM that (same trick as stonesage-image)
        hearth_build = st.pop("build")
        svc["hearth-image"] = {"image": layer_image("hearth", tag), "build": hearth_build, "entrypoint": ["true"], "restart": "no"}
        st["build"] = {"context": build_context("grove", tag), "args": {"BASE_IMAGE": "hearth-image"},
                       "additional_contexts": {"hearth-image": "service:hearth-image"}}
        st["depends_on"] = dict(st.get("depends_on", {}), **{"hearth-image": {"condition": "service_completed_successfully"}})
    st["image"] = "${STONESAGE_IMAGE:-%s}" % layer_image("grove", tag)
    st["environment"].update({
        "STONESAGE_APPS": "hearth,grove",
        "GROVE_WORKER_URL": "http://grove-worker:%d" % WORKER_PORT,
        "GROVE_ENGINE_URL": g["engine_url"], "GROVE_MODEL": g.get("model") or "", "GROVE_RESIDENT": g["resident"],
        "STONESAGE_GROVE_CONTROL_KEY": "${GROVE_CONTROL_KEY:?set GROVE_CONTROL_KEY in .env}",
        "STONESAGE_GROVE_MODEL_KEY": "${GROVE_MODEL_KEY:?set GROVE_MODEL_KEY in .env}"})
    st["networks"] = ["default", "grove-model"]

    def image_build(dockerfile: str) -> Dict[str, Any]:
        return {"build": {"context": build_context("grove", tag), "dockerfile": dockerfile}} if build else {}

    svc["grove-worker"] = {
        "image": "${GROVE_WORKER_IMAGE:-%s}" % layer_image("grove-worker", tag), **image_build("docker/worker.Dockerfile"),
        "restart": "unless-stopped",
        "environment": {
            "GROVE_CONTROL_KEY": "${GROVE_CONTROL_KEY:?set GROVE_CONTROL_KEY in .env}",
            "GROVE_MODEL_KEY": "${GROVE_MODEL_KEY:?set GROVE_MODEL_KEY in .env}",
            "GROVE_MODEL_URL": "http://stonesage:%d/api/garden/v1" % STONESAGE_PORT,
            "GROVE_FETCHER_URL": "http://grove-fetcher:%d" % READER_PORT,
            "GROVE_FETCHER_KEY": "${GROVE_FETCHER_KEY:?set GROVE_FETCHER_KEY in .env}",
            "GROVE_DATA_DIR": "/data", "GROVE_FIRST_RESIDENT": g["resident"]},
        "volumes": ["grove-data:/data"], "networks": ["grove-model", "grove-web"], **_hardened(),
        "healthcheck": {"test": _py_check(WORKER_PORT, "GROVE_CONTROL_KEY"), "interval": "30s", "timeout": "5s", "retries": 5,
                        "start_period": "20s"}}
    svc["grove-fetcher"] = {
        "image": "${GROVE_FETCHER_IMAGE:-%s}" % layer_image("grove-fetcher", tag), **image_build("docker/fetcher.Dockerfile"),
        "restart": "unless-stopped",
        "environment": {"FETCHER_KEY": "${GROVE_FETCHER_KEY:?set GROVE_FETCHER_KEY in .env}",
                        "READER_SEARX_URL": "http://grove-searxng:%d" % SEARX_PORT},
        "networks": ["grove-web", "grove-egress"], **_hardened(),
        "healthcheck": {"test": _py_check(READER_PORT, "FETCHER_KEY"), "interval": "30s", "timeout": "5s", "retries": 5,
                        "start_period": "20s"},
        "depends_on": {"grove-searxng": {"condition": "service_started"}}}
