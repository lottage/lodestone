# ---------------------------------------------------------------------------------------------------- choices ----
def check_resident(resident: str) -> str:
    resident = (resident or DEFAULT_RESIDENT).strip()
    import re
    if not re.fullmatch(r"[a-z0-9-]{1,64}", resident):
        raise GroveError("the first resident's id must be 1-64 characters of a-z, 0-9 and '-' (got %r)" % resident)
    return resident


def model_label(roles: List[Dict[str, Any]]) -> str:
    """A name for the coordinator's model (its file name without .gguf), for the config's `model` field and the board."""
    for r in roles:
        if r.get("name") == "coordinator" and r.get("files"):
            return str(r["files"][0]["file"]).rsplit("/", 1)[-1][:-5] if str(r["files"][0]["file"]).endswith(".gguf") else str(r["files"][0]["file"])
    return ""


def garden_choice(choices: Dict[str, Any], roles: List[Dict[str, Any]], default_engine_url: str, worker_url: str) -> Dict[str, Any]:
    """What the installer writes for Grove: the first resident (unnamed), the model the proxy forwards to (the profile's coordinator
    unless the person picked an endpoint with --garden-engine-url), and the safe settings: the scheduler OFF."""
    engine_url = (choices.get("garden_engine_url") or "").strip() or default_engine_url
    picked = bool((choices.get("garden_engine_url") or "").strip())
    label = (choices.get("garden_model") or "").strip() or ("" if picked else model_label(roles))
    return {"resident": check_resident(choices.get("garden_resident") or DEFAULT_RESIDENT), "engine_url": engine_url, "model": label,
            "worker_url": worker_url}


def grove_config(g: Dict[str, Any], keys: Optional[Dict[str, str]] = None) -> Dict[str, Any]:
    """The `grove` section of StoneSage's config.json. Keys are only written when given (bare metal); the Docker stack passes them
    in the environment instead, so they are not in the file. The scheduler is off: a new install runs a session when asked."""
    section: Dict[str, Any] = {"worker_url": g["worker_url"], "engine_url": g["engine_url"], "resident": g["resident"],
                               "schedule": {"enabled": False}}
    if g.get("model"):
        section["model"] = g["model"]
    if keys:
        section["control_key"] = keys["GROVE_CONTROL_KEY"]
        section["model_key"] = keys["GROVE_MODEL_KEY"]
    return section


def new_keys(have: Optional[Dict[str, str]] = None, names: Tuple[str, ...] = DOCKER_KEYS) -> Dict[str, str]:
    """A random value for each key name; one that already exists is kept (re-running never changes your keys)."""
    have = have or {}
    return {n: (have.get(n) or "").strip() or secrets.token_urlsafe(32) for n in names}


def apps_with_grove(existing: Any) -> List[str]:
    """config `apps` plus grove. No `apps` key means StoneSage's default (hearth), which must stay on, so it is written out."""
    if isinstance(existing, list) and existing:
        return [str(a) for a in existing] + ([] if "grove" in existing else ["grove"])
    return ["hearth", "grove"]


