# ------------------------------------------------------------------------------------------------- bare metal ----
def parse_stonesage(url: str) -> Tuple[str, str, int]:
    """(base url, host, port) of the cockpit the worker may call. nftables rules need an address, so the host must be an IP."""
    u = urlparse((url or "").strip() or "http://127.0.0.1:%d" % STONESAGE_PORT)
    if u.scheme not in ("http", "https") or not u.hostname:
        raise GroveError("--garden-stonesage-url must be an http(s) URL like http://127.0.0.1:8888 (got %r)" % url)
    try:
        ipaddress.ip_address(u.hostname)
    except ValueError:
        raise GroveError("--garden-stonesage-url must name an IP address, not a host name: the firewall rule that confines the "
                         "worker is written for that address (got %r)" % u.hostname)
    port = u.port or (443 if u.scheme == "https" else 80)
    return "%s://%s:%d" % (u.scheme, u.hostname if ":" not in u.hostname else "[%s]" % u.hostname, port), u.hostname, port


