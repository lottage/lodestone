def firewall_script() -> str:
    """grove-firewall.sh: DOCKER-USER rules for the reader's network. Idempotent (re-running replaces the rules), `--remove` takes
    them out. Needs root. It makes the chain if Docker has not yet (Docker keeps an existing DOCKER-USER)."""
    v4 = " ".join(PRIVATE_V4)
    return """#!/bin/sh
# Grove's firewall for the reader's Docker network (generated by lodestone.installer --with-garden; review it before you run it).
#
# What it does, for traffic that comes from containers on the bridge %(bridge)s (grove-fetcher and grove-searxng):
#   1. traffic between containers on that network is allowed;
#   2. IPv4 to private, CGNAT, link-local, loopback, multicast and reserved destinations is DROPPED;
#   3. all IPv6 from that bridge is dropped (the network has none; this holds if the daemon ever gives it some);
#   4. new connections from that bridge to THIS HOST are dropped (the containers need nothing here).
# Everything else (the public internet) is forwarded as Docker does. Nothing else on the machine is touched.
#
#   sudo sh %(script)s            apply        sudo sh %(script)s --remove     take the rules out
# DOCKER-USER rules do not survive a reboot. %(unit)s next to this file re-applies them before Docker starts:
#   sudo cp %(unit)s /etc/systemd/system/ && sudo systemctl daemon-reload && sudo systemctl enable %(unit)s
set -eu
BRIDGE=%(bridge)s
CHAIN=GROVE-EGRESS
PRIVATE="%(v4)s"

[ "$(id -u)" = 0 ] || { echo "grove-firewall: run as root (sudo sh $0)" >&2; exit 1; }
command -v iptables >/dev/null || { echo "grove-firewall: iptables not found" >&2; exit 1; }

remove() {
    for ipt in iptables ip6tables; do
        command -v "$ipt" >/dev/null || continue
        while "$ipt" -D DOCKER-USER -i "$BRIDGE" -j "$CHAIN" 2>/dev/null; do :; done
        "$ipt" -F "$CHAIN" 2>/dev/null || true
        "$ipt" -X "$CHAIN" 2>/dev/null || true
        while "$ipt" -D INPUT -i "$BRIDGE" -m conntrack --ctstate NEW -j DROP 2>/dev/null; do :; done
    done
}

remove
[ "${1:-}" = "--remove" ] && { echo "grove-firewall: rules removed"; exit 0; }

# IPv4
iptables -N DOCKER-USER 2>/dev/null || true
iptables -N "$CHAIN"
iptables -A "$CHAIN" -i "$BRIDGE" -o "$BRIDGE" -j ACCEPT
for net in $PRIVATE; do
    iptables -A "$CHAIN" -i "$BRIDGE" -d "$net" -j DROP
done
iptables -A "$CHAIN" -j RETURN
iptables -I DOCKER-USER 1 -i "$BRIDGE" -j "$CHAIN"
iptables -I INPUT 1 -i "$BRIDGE" -m conntrack --ctstate NEW -j DROP

# IPv6
if command -v ip6tables >/dev/null; then
    ip6tables -N DOCKER-USER 2>/dev/null || true
    ip6tables -N "$CHAIN"
    ip6tables -A "$CHAIN" -i "$BRIDGE" -o "$BRIDGE" -j ACCEPT
    ip6tables -A "$CHAIN" -i "$BRIDGE" -j DROP
    ip6tables -I DOCKER-USER 1 -i "$BRIDGE" -j "$CHAIN"
    ip6tables -I INPUT 1 -i "$BRIDGE" -m conntrack --ctstate NEW -j DROP
fi
echo "grove-firewall: rules in place for $BRIDGE (check: iptables -S $CHAIN)"
""" % {"bridge": EGRESS_BRIDGE, "script": FIREWALL_SCRIPT, "unit": FIREWALL_UNIT, "v4": v4}


