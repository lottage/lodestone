"""Grove for Lodestone's installer: `--with-garden` (Grove is the optional agents add-on; its public repository is `grove`).

Pure rendering, standard library only, nothing is run or written here: installer.py calls these functions to add Grove to the
Docker Compose stack (docker_*) and to the bare-metal plan (native_*), and the tests read what they return.

What Grove is, for the installer: a WORKER that holds the residents (agents with a name, works, a journal), a READER that fetches
public web pages for them (with SearXNG for search), and a plugin inside StoneSage (a board, the model proxy, the scheduler). The
point of the walls: the worker may reach the cockpit's model proxy and the reader and nothing else; the reader may reach the public
internet and nothing private. The walls are the network (Docker: internal networks and a firewall on the reader's network;
bare metal: an nftables table keyed on the users) PLUS the code of the reader, which refuses private addresses itself.

    Docker       networks   grove-model (internal)  stonesage <-> grove-worker
                            grove-web   (internal)  grove-worker <-> grove-fetcher
                            grove-egress (bridge)   grove-fetcher, grove-searxng -> the internet, filtered by grove-firewall.sh
    Bare metal   users      grove (the worker), grovereader (the reader); grove-nft.conf limits what each may connect to

On one machine the bare-metal walls rest on the host firewall and on user separation. They are weaker than separate machines or
containers: a root compromise, a firewall that is not loaded, or a mistake in the rules removes them. The README says so.
"""

